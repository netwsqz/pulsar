package com.example.pulsar.data.jellyfin

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

class JellyfinUrlBuilderTest {
    @Test
    fun `normalizes trailing slash from HTTPS base URL`() {
        val builder = JellyfinUrlBuilder("  https://media.example.com///  ")

        assertEquals(
            "https://media.example.com/Users/user-1/Items",
            builder.itemsUrl("user-1")
        )
    }

    @Test
    fun `allows HTTP for private network and loopback hosts`() {
        val allowedUrls = listOf(
            "http://localhost:8096",
            "http://LOCALHOST:8096",
            "http://127.0.0.1:8096",
            "http://10.0.0.1:8096",
            "http://172.16.0.1:8096",
            "http://172.31.255.255:8096",
            "http://192.168.1.2:8096",
            // CGNAT 保留段（Tailscale 等）100.64.0.0/10：段内首尾 + 段中任取
            "http://100.64.0.1:8096",
            "http://100.100.50.50:8096",
            "http://100.127.255.255:8096",
            "http://[::1]:8096",
            "http://[fe80::1]:8096",
            "http://[fd00::1]:8096"
        )

        allowedUrls.forEach { url ->
            assertTrue(JellyfinUrlBuilder(url).loginUrl().startsWith(url))
        }
    }

    @Test
    fun `rejects HTTP for public and ambiguous hosts`() {
        val rejectedUrls = listOf(
            "http://media.example.com",
            "http://8.8.8.8",
            "http://172.15.255.255",
            "http://172.32.0.0",
            "http://169.254.1.1",
            // CGNAT 段外沿（100.0-63.x 与 100.128+ 属公网）仍要拒绝
            "http://100.63.255.255",
            "http://100.128.0.1",
            "http://0.0.0.0",
            "http://localhost.evil",
            "http://jellyfin.local",
            "http://[2001:db8::1]"
        )

        rejectedUrls.forEach { url ->
            assertTrue(runCatching { JellyfinUrlBuilder(url) }.isFailure)
        }
    }

    @Test(expected = IllegalArgumentException::class)
    fun `rejects blank base URL`() {
        JellyfinUrlBuilder("   ")
    }

    @Test(expected = IllegalArgumentException::class)
    fun `rejects base URL without a host`() {
        JellyfinUrlBuilder("https:///jellyfin")
    }

    @Test
    fun `builds login URL without credentials`() {
        assertEquals(
            "https://media.example.com/Users/AuthenticateByName",
            JellyfinUrlBuilder("https://media.example.com").loginUrl()
        )
    }

    @Test
    fun `builds media stream request with MediaBrowser authorization header`() {
        val builder = JellyfinUrlBuilder("https://media.example.com/jellyfin/")

        val request = builder.mediaStreamRequest("movie-42", "secret-token", "device-abc")

        assertEquals(
            "https://media.example.com/jellyfin/Videos/movie-42/stream?static=true",
            request.url
        )
        assertEquals(
            "MediaBrowser Client=\"Pulsar\", Device=\"Android\", DeviceId=\"device-abc\", " +
                "Version=\"0.1.0\", Token=\"secret-token\"",
            request.headers["Authorization"]
        )
        assertFalse(request.url.contains("secret-token"))
    }

    @Test
    fun `does not place token in any URL generated by the builder`() {
        val token = "token-with-special-characters-?&="
        val builder = JellyfinUrlBuilder("https://media.example.com")

        val request = builder.mediaStreamRequest("item-1", token, "device-abc")

        assertTrue(
            request.headers.values.any {
                it == "MediaBrowser Client=\"Pulsar\", Device=\"Android\", DeviceId=\"device-abc\", " +
                    "Version=\"0.1.0\", Token=\"$token\""
            }
        )
        assertFalse(request.url.contains(token))
        assertFalse(request.url.contains("api_key"))
    }

    @Test(expected = IllegalArgumentException::class)
    fun `rejects blank media ID`() {
        JellyfinUrlBuilder("https://media.example.com").mediaStreamRequest("  ", "token", "device-abc")
    }

    @Test(expected = IllegalArgumentException::class)
    fun `rejects blank device ID`() {
        JellyfinUrlBuilder("https://media.example.com").mediaStreamRequest("item-1", "token", "  ")
    }

    @Test(expected = IllegalArgumentException::class)
    fun `rejects blank user ID`() {
        JellyfinUrlBuilder("https://media.example.com").itemsUrl("\n")
    }

    @Test
    fun `encodes IDs as path segments`() {
        val builder = JellyfinUrlBuilder("https://media.example.com")

        val url = builder.mediaStreamRequest("episode 1/2", "token", "device-abc").url

        assertEquals(
            "https://media.example.com/Videos/episode%201%2F2/stream?static=true",
            url
        )
    }

    @Test
    fun `builds image request with encoded tag and MediaBrowser authorization header`() {
        val builder = JellyfinUrlBuilder("https://media.example.com/jellyfin/")

        val request = builder.imageRequest("album-1", "abc+/=", "secret-token", "device-abc")

        assertEquals(
            "https://media.example.com/jellyfin/Items/album-1/Images/Primary?tag=abc%2B%2F%3D",
            request.url
        )
        assertEquals(
            "MediaBrowser Client=\"Pulsar\", Device=\"Android\", DeviceId=\"device-abc\", " +
                "Version=\"0.1.0\", Token=\"secret-token\"",
            request.headers["Authorization"]
        )
        assertFalse(request.url.contains("secret-token"))
    }

    @Test
    fun `image request omits tag query when image tag is blank`() {
        val builder = JellyfinUrlBuilder("https://media.example.com")

        val request = builder.imageRequest("album-1", null, "token", "device-abc")

        assertEquals(
            "https://media.example.com/Items/album-1/Images/Primary",
            request.url
        )
    }

    @Test(expected = IllegalArgumentException::class)
    fun `rejects blank image item ID`() {
        JellyfinUrlBuilder("https://media.example.com").imageRequest("  ", "tag", "token", "device-abc")
    }

    @Test(expected = IllegalArgumentException::class)
    fun `rejects blank image request token`() {
        JellyfinUrlBuilder("https://media.example.com").imageRequest("album-1", "tag", "  ", "device-abc")
    }

    @Test(expected = IllegalArgumentException::class)
    fun `rejects blank image request device ID`() {
        JellyfinUrlBuilder("https://media.example.com").imageRequest("album-1", "tag", "token", "  ")
    }
}
