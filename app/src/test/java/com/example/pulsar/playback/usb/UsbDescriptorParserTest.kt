package com.example.pulsar.playback.usb

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * [UsbDescriptorParser] 的单元测试。
 *
 * fixture 是手工按 USB Audio Class 1.0/2.0 规范构造的配置描述符字节流：
 * - UAC1 设备（如常见 USB 声卡）：2ch / 16bit，采样率 44.1k + 48k
 * - UAC2 设备（如小尾巴）：2ch / 24bit，采样率在时钟实体上（描述符内无）
 * - 多 alt setting 设备：同一接口 alt1=16bit、alt2=24bit，alt2 带反馈端点
 */
class UsbDescriptorParserTest {

    /** 把若干 0..255 的整数按序转成字节数组（0x80 以上自动取反为负数）。 */
    private fun b(vararg ints: Int): ByteArray = ByteArray(ints.size) { ints[it].toByte() }

    // ---- fixture：UAC1，2ch/16bit，采样率 44.1k+48k ---------------------------

    private val uac1Config = b(
        // Configuration：wTotalLength=0x004B，1 个接口，1 个配置
        0x09, 0x02, 0x4B, 0x00, 0x01, 0x01, 0x00, 0x80, 0x32,
        // 接口 0：AudioControl（class=1, subclass=1, protocol=0）
        0x09, 0x04, 0x00, 0x00, 0x00, 0x01, 0x01, 0x00, 0x00,
        // 类特定 AC header（UAC1, bcdADC=0x0100）
        0x09, 0x24, 0x01, 0x00, 0x01, 0x00, 0x09, 0x00, 0x00,
        // 接口 1 alt 0：AudioStreaming 零带宽（无端点）
        0x09, 0x04, 0x01, 0x00, 0x00, 0x01, 0x02, 0x00, 0x00,
        // 接口 1 alt 1：有效流接口
        0x09, 0x04, 0x01, 0x01, 0x01, 0x01, 0x02, 0x00, 0x00,
        // 类特定 AS_GENERAL（UAC1）：wFormatTag=0x0001（PCM）
        0x07, 0x24, 0x01, 0x01, 0x01, 0x01, 0x00,
        // 类特定 FORMAT_TYPE（UAC1）：PCM, 2ch, 2B/帧, 16bit, 2 个采样率 [44.1k, 48k]
        0x0E, 0x24, 0x02, 0x01, 0x02, 0x02, 0x10, 0x02, 0x44, 0xAC, 0x00, 0x80, 0xBB, 0x00,
        // 端点：OUT1，iso+adaptive，wMaxPacketSize=0x0100（256），bInterval=1
        0x09, 0x05, 0x01, 0x09, 0x00, 0x01, 0x01, 0x00, 0x00,
    )

    // ---- fixture：UAC2，2ch/24bit，采样率描述符内无 ---------------------------

    private val uac2Config = b(
        // Configuration：wTotalLength=0x0043
        0x09, 0x02, 0x43, 0x00, 0x01, 0x01, 0x00, 0x80, 0x32,
        // 接口 0：AudioControl（protocol=0x20 → UAC2）
        0x09, 0x04, 0x00, 0x00, 0x00, 0x01, 0x01, 0x20, 0x00,
        // 接口 1 alt 0：零带宽
        0x09, 0x04, 0x01, 0x00, 0x00, 0x01, 0x02, 0x20, 0x00,
        // 接口 1 alt 1：有效流接口
        0x09, 0x04, 0x01, 0x01, 0x01, 0x01, 0x02, 0x20, 0x00,
        // 类特定 AS_GENERAL（UAC2，规范 16 字节 Table 4-27）：bTerminalLink=1,
        // bNrChannels=2（索引 10），bmChannelConfig=0x00000003（索引 11-14）
        0x10, 0x24, 0x01, 0x01, 0x00, 0x01, 0x01, 0x00, 0x00, 0x00, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00,
        // 类特定 FORMAT_TYPE_I（UAC2）：subslot=3B, 24bit
        0x06, 0x24, 0x02, 0x01, 0x03, 0x18,
        // 端点：OUT1，iso+async，wMaxPacketSize=0x0400（1024），bInterval=1
        0x09, 0x05, 0x01, 0x05, 0x00, 0x04, 0x01, 0x00, 0x00,
    )

    // ---- fixture：UAC2 多 alt setting，alt1=16bit，alt2=24bit 带反馈端点 -------

    private val uac2MultiConfig = b(
        // Configuration：wTotalLength=0x006B
        0x09, 0x02, 0x6B, 0x00, 0x01, 0x01, 0x00, 0x80, 0x32,
        // 接口 0：AudioControl
        0x09, 0x04, 0x00, 0x00, 0x00, 0x01, 0x01, 0x20, 0x00,
        // 接口 1 alt 0：零带宽
        0x09, 0x04, 0x01, 0x00, 0x00, 0x01, 0x02, 0x20, 0x00,
        // --- alt 1：16bit，无反馈端点 ---
        0x09, 0x04, 0x01, 0x01, 0x01, 0x01, 0x02, 0x20, 0x00,
        0x10, 0x24, 0x01, 0x01, 0x00, 0x01, 0x01, 0x00, 0x00, 0x00, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00,
        0x06, 0x24, 0x02, 0x01, 0x02, 0x10,
        0x09, 0x05, 0x01, 0x05, 0x00, 0x02, 0x01, 0x00, 0x00,
        // --- alt 2：24bit，反馈端点 bSynchAddress=0x81 ---
        0x09, 0x04, 0x01, 0x02, 0x01, 0x01, 0x02, 0x20, 0x00,
        0x10, 0x24, 0x01, 0x01, 0x00, 0x01, 0x01, 0x00, 0x00, 0x00, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00,
        0x06, 0x24, 0x02, 0x01, 0x03, 0x18,
        0x09, 0x05, 0x01, 0x05, 0x00, 0x04, 0x01, 0x00, 0x81,
    )

    // ---- fixture：UAC2 完整 AC 接口（输入终端 → 时钟源），验证 clockId 反查 -------

    private val uac2ClockConfig = b(
        // Configuration：wTotalLength=0x0065
        0x09, 0x02, 0x65, 0x00, 0x01, 0x01, 0x00, 0x80, 0x32,
        // 接口 0：AudioControl（UAC2）
        0x09, 0x04, 0x00, 0x00, 0x00, 0x01, 0x01, 0x20, 0x00,
        // AC header（bcdADC=0x0200）
        0x09, 0x24, 0x01, 0x00, 0x02, 0x00, 0x18, 0x00, 0x00,
        // Clock Source：bClockID=0x03
        0x08, 0x24, 0x0A, 0x03, 0x00, 0x01, 0x00, 0x00,
        // Input Terminal：bTerminalID=0x02，bCSourceID=0x03
        0x11, 0x24, 0x02, 0x02, 0x01, 0x01, 0x00, 0x03, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        // 接口 1 alt 0：零带宽
        0x09, 0x04, 0x01, 0x00, 0x00, 0x01, 0x02, 0x20, 0x00,
        // 接口 1 alt 1：有效流接口，AS_GENERAL bTerminalLink=0x02
        0x09, 0x04, 0x01, 0x01, 0x01, 0x01, 0x02, 0x20, 0x00,
        0x10, 0x24, 0x01, 0x02, 0x00, 0x01, 0x01, 0x00, 0x00, 0x00, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00,
        0x06, 0x24, 0x02, 0x01, 0x03, 0x18,
        0x09, 0x05, 0x01, 0x05, 0x00, 0x04, 0x01, 0x00, 0x00,
    )

    // ---- fixture：UAC2，AudioControl 接口号非零（验证 SET_CUR 的 wIndex 低字节） ----

    private val uac2NonZeroAcInterface = b(
        // Configuration：wTotalLength=0x0043
        0x09, 0x02, 0x43, 0x00, 0x01, 0x01, 0x00, 0x80, 0x32,
        // 接口 2：AudioControl（UAC2）——bInterfaceNumber=2，非零
        0x09, 0x04, 0x02, 0x00, 0x00, 0x01, 0x01, 0x20, 0x00,
        // 接口 3 alt 0：零带宽
        0x09, 0x04, 0x03, 0x00, 0x00, 0x01, 0x02, 0x20, 0x00,
        // 接口 3 alt 1：有效流接口
        0x09, 0x04, 0x03, 0x01, 0x01, 0x01, 0x02, 0x20, 0x00,
        // 类特定 AS_GENERAL（UAC2，16 字节）：bNrChannels=2（偏移 10），bmChannelConfig=0x03（偏移 11-14）
        0x10, 0x24, 0x01, 0x01, 0x00, 0x01, 0x01, 0x00, 0x00, 0x00, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00,
        // 类特定 FORMAT_TYPE_I（UAC2）：subslot=3B, 24bit
        0x06, 0x24, 0x02, 0x01, 0x03, 0x18,
        // 端点：OUT1，iso+async，wMaxPacketSize=0x0400（1024），bInterval=1
        0x09, 0x05, 0x01, 0x05, 0x00, 0x04, 0x01, 0x00, 0x00,
    )

    @Test
    fun `解析 UAC1 设备得到一个 16bit 双采样率格式`() {
        val formats = UsbDescriptorParser.parse(uac1Config)

        assertEquals(1, formats.size)
        val f = formats.single()
        assertEquals(0x0100, f.uacVersion)
        assertTrue(!f.isUac2)
        assertEquals(1, f.interfaceNumber)
        assertEquals(1, f.altSetting)
        assertEquals(0x01, f.endpointAddress)
        assertEquals(256, f.maxPacketSize)
        assertEquals(1, f.bInterval)
        assertEquals(0, f.bSynchAddress)
        assertEquals(2, f.channels)
        assertEquals(16, f.bitsPerSample)
        assertEquals(2, f.subframeSize)
        assertEquals(listOf(44100, 48000), f.sampleRates)
        assertEquals(0, f.controlInterfaceNumber)
    }

    @Test
    fun `解析 UAC2 设备得到一个 24bit 格式且采样率列表为空`() {
        val formats = UsbDescriptorParser.parse(uac2Config)

        assertEquals(1, formats.size)
        val f = formats.single()
        assertEquals(0x0200, f.uacVersion)
        assertTrue(f.isUac2)
        assertEquals(1, f.interfaceNumber)
        assertEquals(1, f.altSetting)
        assertEquals(0x01, f.endpointAddress)
        assertEquals(1024, f.maxPacketSize)
        assertEquals(2, f.channels)
        assertEquals(24, f.bitsPerSample)
        assertEquals(3, f.subframeSize)
        assertTrue(f.sampleRates.isEmpty())
        assertEquals(0, f.controlInterfaceNumber)
    }

    @Test
    fun `AudioControl 接口号非零时被捕获为 controlInterfaceNumber`() {
        val formats = UsbDescriptorParser.parse(uac2NonZeroAcInterface)

        val f = formats.single()
        assertEquals(3, f.interfaceNumber)
        assertEquals(2, f.controlInterfaceNumber)
        assertEquals(24, f.bitsPerSample)
    }

    @Test
    fun `UAC2 通过输入终端到时钟源映射反查得到 clockId`() {
        val formats = UsbDescriptorParser.parse(uac2ClockConfig)

        val f = formats.single()
        assertEquals(3, f.clockId)   // AS_GENERAL bTerminalLink=2 → Input Terminal 2 → Clock Source 3
        assertEquals(24, f.bitsPerSample)
        assertEquals(2, f.channels)
    }

    @Test
    fun `UAC1 没有时钟实体 clockId 为 0`() {
        val f = UsbDescriptorParser.parse(uac1Config).single()
        assertEquals(0, f.clockId)
    }

    @Test
    fun `解析多 alt setting 设备得到两个格式并跳过零带宽`() {
        val formats = UsbDescriptorParser.parse(uac2MultiConfig)

        assertEquals(2, formats.size)
        val byAlt = formats.associateBy { it.altSetting }
        assertEquals(16, byAlt.getValue(1).bitsPerSample)
        assertEquals(0, byAlt.getValue(1).bSynchAddress)
        assertEquals(24, byAlt.getValue(2).bitsPerSample)
        assertEquals(0x81, byAlt.getValue(2).bSynchAddress)
        assertEquals(512, byAlt.getValue(1).maxPacketSize)
        assertEquals(1024, byAlt.getValue(2).maxPacketSize)
    }

    // ---- 回归 fixture：真机 CX31993 类小尾巴，2ch，bmChannelConfig=0x03（前左|前右）----
    // 旧 bug：bNrChannels 误读偏移 11（bmChannelConfig 低字节）→ 立体声被读成 3ch。
    // 此 fixture 让 bNrChannels(偏移10)=2 与 bmChannelConfig 低字节=3 明确不同，
    // 断言解析结果必须是 2，锁定偏移修正（bNrChannels 在偏移 10）。
    private val uac2StereoChannelConfig = b(
        // Configuration：wTotalLength=0x0043
        0x09, 0x02, 0x43, 0x00, 0x01, 0x01, 0x00, 0x80, 0x32,
        // 接口 0：AudioControl（UAC2）
        0x09, 0x04, 0x00, 0x00, 0x00, 0x01, 0x01, 0x20, 0x00,
        // 接口 1 alt 0：零带宽
        0x09, 0x04, 0x01, 0x00, 0x00, 0x01, 0x02, 0x20, 0x00,
        // 接口 1 alt 1：有效流接口
        0x09, 0x04, 0x01, 0x01, 0x01, 0x01, 0x02, 0x20, 0x00,
        // AS_GENERAL（16 字节）：bNrChannels=2（偏移10），bmChannelConfig=0x00000003（偏移11-14，低字节=3）
        0x10, 0x24, 0x01, 0x01, 0x00, 0x01, 0x01, 0x00, 0x00, 0x00, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00,
        // FORMAT_TYPE_I（UAC2）：subslot=3B, 24bit
        0x06, 0x24, 0x02, 0x01, 0x03, 0x18,
        // 端点：OUT1，iso+async
        0x09, 0x05, 0x01, 0x05, 0x00, 0x04, 0x01, 0x00, 0x00,
    )

    @Test
    fun `UAC2 立体声不会因 bmChannelConfig 被误读成 3 声道`() {
        val f = UsbDescriptorParser.parse(uac2StereoChannelConfig).single()
        // 旧 bug 会读到 bmChannelConfig 低字节 3；正确应读 bNrChannels = 2。
        assertEquals(2, f.channels)
    }

    @Test
    fun `空字节流返回空列表`() {
        assertTrue(UsbDescriptorParser.parse(ByteArray(0)).isEmpty())
    }

    private fun uac2FeatureUnitConfig(
        masterControls: Int,
        leftControls: Int = 0,
        rightControls: Int = 0,
    ) = b(
        // Configuration：wTotalLength=0x007B
        0x09, 0x02, 0x7B, 0x00, 0x02, 0x01, 0x00, 0x80, 0x32,
        // 接口 0：AudioControl（UAC2）
        0x09, 0x04, 0x00, 0x00, 0x00, 0x01, 0x01, 0x20, 0x00,
        0x09, 0x24, 0x01, 0x00, 0x02, 0x00, 0x38, 0x00, 0x00,
        // Input Terminal：ID=2，Clock Source=3，2ch
        0x11, 0x24, 0x02, 0x02, 0x01, 0x01, 0x00, 0x03, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        // Feature Unit：ID=5，Source=2；每个 bmaControls 固定为 4 字节。
        0x12, 0x24, 0x06, 0x05, 0x02,
        masterControls, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00,
        0x00,
        // Output Terminal：ID=6，Source=5，Clock Source=3
        0x0C, 0x24, 0x03, 0x06, 0x01, 0x03, 0x00, 0x05, 0x03, 0x00, 0x00, 0x00,
        // 接口 1 alt 0 / alt 1，AS_GENERAL 的 TerminalLink=2。
        0x09, 0x04, 0x01, 0x00, 0x00, 0x01, 0x02, 0x20, 0x00,
        0x09, 0x04, 0x01, 0x01, 0x01, 0x01, 0x02, 0x20, 0x00,
        0x10, 0x24, 0x01, 0x02, 0x00, 0x01, 0x01, 0x00, 0x00, 0x00, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00,
        0x06, 0x24, 0x02, 0x01, 0x02, 0x10,
        0x09, 0x05, 0x01, 0x05, 0x00, 0x02, 0x01, 0x00, 0x00,
    )

    @Test
    fun `UAC2 主声道无音量但左右声道可写时仍识别硬件音量`() {
        val config = uac2FeatureUnitConfig(masterControls = 0)
        // Feature Unit 起始偏移 44；bmaControls[1]/[2] 位于 +9/+13。
        config[53] = 0x0C
        config[57] = 0x0C

        val format = UsbDescriptorParser.parse(config).single()

        assertEquals(0x05, format.featureUnitId)
        assertEquals(0x06, format.volumeChannelMask)
        assertTrue(format.hasHardwareVolume)
    }

    @Test
    fun `UAC2 所有声道不可写时不声明硬件音量`() {
        val format = UsbDescriptorParser.parse(uac2FeatureUnitConfig(masterControls = 0)).single()

        assertEquals(0, format.featureUnitId)
        assertEquals(0, format.volumeChannelMask)
        assertTrue(!format.hasHardwareVolume)
    }
    @Test
    fun `UAC2 可读写主音量 Feature Unit 关联到对应流格式`() {
        val format = UsbDescriptorParser.parse(
            uac2FeatureUnitConfig(masterControls = 0x0C),
        ).single()

        assertEquals(0x05, format.featureUnitId)
        assertTrue(format.hasHardwareVolume)
    }

    @Test
    fun `UAC2 只读主音量不声明可设置硬件音量`() {
        val format = UsbDescriptorParser.parse(
            uac2FeatureUnitConfig(masterControls = 0x04),
        ).single()

        assertEquals(0, format.featureUnitId)
        assertTrue(!format.hasHardwareVolume)
    }

    @Test
    fun `多个 UAC2 Audio Function 的控制接口与 Feature Unit 不串用`() {
        val config = b(
            0x09, 0x02, 0xB1, 0x00, 0x04, 0x01, 0x00, 0x80, 0x32,
            // Function 1：AC=0、AS=1、Feature Unit=5。
            0x08, 0x0B, 0x00, 0x02, 0x01, 0x00, 0x20, 0x00,
            0x09, 0x04, 0x00, 0x00, 0x00, 0x01, 0x01, 0x20, 0x00,
            0x11, 0x24, 0x02, 0x02, 0x01, 0x01, 0x00, 0x03, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x0A, 0x24, 0x06, 0x05, 0x02, 0x0C, 0x00, 0x00, 0x00, 0x00,
            0x09, 0x04, 0x01, 0x01, 0x01, 0x01, 0x02, 0x20, 0x00,
            0x10, 0x24, 0x01, 0x02, 0x00, 0x01, 0x01, 0x00, 0x00, 0x00, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00,
            0x06, 0x24, 0x02, 0x01, 0x02, 0x10,
            0x09, 0x05, 0x01, 0x05, 0x00, 0x02, 0x01, 0x00, 0x00,
            // Function 2：复用 Terminal ID=2，但 AC=2、AS=3、Feature Unit=9。
            0x08, 0x0B, 0x02, 0x02, 0x01, 0x00, 0x20, 0x00,
            0x09, 0x04, 0x02, 0x00, 0x00, 0x01, 0x01, 0x20, 0x00,
            0x11, 0x24, 0x02, 0x02, 0x01, 0x01, 0x00, 0x07, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x0A, 0x24, 0x06, 0x09, 0x02, 0x0C, 0x00, 0x00, 0x00, 0x00,
            0x09, 0x04, 0x03, 0x01, 0x01, 0x01, 0x02, 0x20, 0x00,
            0x10, 0x24, 0x01, 0x02, 0x00, 0x01, 0x01, 0x00, 0x00, 0x00, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00,
            0x06, 0x24, 0x02, 0x01, 0x02, 0x10,
            0x09, 0x05, 0x02, 0x05, 0x00, 0x02, 0x01, 0x00, 0x00,
        )

        val formats = UsbDescriptorParser.parse(config).associateBy { it.interfaceNumber }

        assertEquals(0, formats.getValue(1).controlInterfaceNumber)
        assertEquals(3, formats.getValue(1).clockId)
        assertEquals(5, formats.getValue(1).featureUnitId)
        assertEquals(2, formats.getValue(3).controlInterfaceNumber)
        assertEquals(7, formats.getValue(3).clockId)
        assertEquals(9, formats.getValue(3).featureUnitId)
    }

    @Test
    fun `截断的描述符不会崩溃`() {
        // 配置头 wTotalLength 声称 0x4B，但实际字节更少——解析应安全停止。
        val truncated = uac1Config.copyOfRange(0, 20)
        // 不抛异常即可，返回什么都可以
        UsbDescriptorParser.parse(truncated)
    }
}
